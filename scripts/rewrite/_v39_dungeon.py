# 构建JS
def build_js():
    parts = []
    # 先输出BOSS敌人定义
    boss_lines = []
    for bid, bdata in BOSS_ENEMIES.items():
        skills = ",".join('"%s"' % s for s in bdata["skills"])
        boss_lines.append('"%s": {"cn":"%s","realm":%d,"power":%d,"hp":%d,"atk":%d,"def":%d,"skills":[%s],"loot":{"gold":%d,"xp":%d,"mat":"%s"},"desc":"%s"}' % (
            bid, bdata["cn"], bdata["realm"], bdata["power"], bdata["hp"], bdata["atk"], bdata["def"], skills,
            bdata["loot"]["gold"], bdata["loot"]["xp"], bdata["loot"]["mat"], bdata["desc"]))
    parts.append("// v39 方向二：BOSS敌人定义\nENEMIES = Object.assign({}, ENEMIES, {\n%s\n});" % ",\n".join(boss_lines))

    # 节点定义
    for nid, place, text, opts in NODES:
        text_lines = ",\n".join('"%s"' % t.replace('"','「') for t in text)
        opt_lines = []
        for o in opts:
            if o.get("run") == "startCombat":
                # 需要从节点ID推断敌人ID
                enemy_map = {
                    "dun_books_boss": ("dun_books_boss","禁书化身·墨噬"),
                    "dun_ruins_boss": ("dun_ruins_boss","遗迹守卫·石魇"),
                    "dun_tower_boss": ("dun_tower_boss","灵魂看守·魂缚者"),
                    "dun_mine_boss": ("dun_mine_boss","矿脉意志·熔岩之心"),
                    "dun_arena_boss": ("dun_arena_boss","战魂守卫"),
                    "dun_tree_boss": ("dun_tree_boss","腐根精"),
                }
                eid, ename = enemy_map.get(nid, (nid, "未知敌人"))
                after_map = {
                    "dun_books_boss": "dun_books_treasure",
                    "dun_ruins_boss": "dun_ruins_treasure",
                    "dun_tower_boss": "dun_tower_treasure",
                    "dun_mine_boss": "dun_mine_3",
                    "dun_arena_boss": "dun_arena_treasure",
                    "dun_tree_boss": "dun_tree_treasure",
                }
                after = after_map.get(nid, "dungeon_hub")
                opt_lines.append('{t:"%s", run:function(){ startCombat("%s","%s","%s"); }}' % (o["t"], eid, ename, after))
            else:
                opt_lines.append('{t:"%s", go:"%s"}' % (o["t"].replace('"','「'), o["go"]))
        block = '''N["%s"]=function(){return{
place:"%s",
text:[
%s
],
options:[
%s
]
}};''' % (nid, place, text_lines, ",\n".join(opt_lines))
        parts.append(block)
    return "\n\n".join(parts)

if __name__ == '__main__':
    js_code = build_js()
    header = "\n\n// ============================================================\n// v39 方向二：地下城与BOSS战（6副本+枢纽，%d节点）\n// ============================================================\n\n" % len(NODES)
    js_code = header + js_code

    with open('game.html','r',encoding='utf-8') as f:
        html = f.read()

    pos = html.rfind('</script>')
    if pos > 0:
        html = html[:pos] + js_code + "\n\n" + html[pos:]
        with open('game.html','w',encoding='utf-8') as f:
            f.write(html)
        print('✓ 已插入地下城系统（{}节点 + {}个BOSS）'.format(len(NODES), len(BOSS_ENEMIES)))
    else:
        print('✗ 未找到插入位置')
