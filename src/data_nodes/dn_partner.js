    if(!combat && !node.tag) return null;
    if(!window.__p1done) window.__p1done = {};
    var k = (node.id||"") + ":" + String(node.place||"");
    if(window.__p1done[k]) return null;
    var base;
    if(rel <= -20) base = "老铁没看你。他把铁砧上那根烧红的料子夹起来，抡起锤子砸了三下，火星溅到你脚边——他没说错话，也没说对的话。";
