def js_str(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'

def get_block(t, nid):
    m = re.search(r'N\["' + re.escape(nid) + r'"\]\s*=\s*\{', t)
    if not m: return None
    start = m.start(); d = 0; i = m.end() - 1
    while i < len(t):
        if t[i] == '{': d += 1
        elif t[i] == '}':
            d -= 1
            if d == 0:
                end = t.find(';', i); break
        i += 1
    return (t[start:end], start, end)

